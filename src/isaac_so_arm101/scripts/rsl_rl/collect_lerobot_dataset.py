def _get_action_bounds(env, device: torch.device) -> tuple[torch.Tensor, torch.Tensor]:
    action_space = env.unwrapped.single_action_space
    low = torch.as_tensor(action_space.low, dtype=torch.float32, device=device)
    high = torch.as_tensor(action_space.high, dtype=torch.float32, device=device)
    low = torch.where(torch.isfinite(low), low, torch.full_like(low, -3.2))
    high = torch.where(torch.isfinite(high), high, torch.full_like(high, 3.2))
    return low, high


def _build_policy_client(env, task_type: str, policy_backend: str, policy_ckpt: str, action_horizon: int):
    camera_infos = {
        k: sensor.image_shape for k, sensor in env.unwrapped.scene.sensors.items() if isinstance(sensor, Camera)
    }
    if not camera_infos:
        raise RuntimeError("No camera sensors found for SmolVLA base policy.")
    if policy_backend == "local":
        return LocalSmolVLAPolicy(
            pretrained_name_or_path=policy_ckpt,
            device=args_cli.device,
            actions_per_chunk=action_horizon,
        )
    service_kwargs = dict(
        host=args_cli.residual_policy_host,
        port=args_cli.residual_policy_port,
        timeout_ms=args_cli.residual_policy_timeout_ms,
        camera_infos=camera_infos,
        task_type=task_type,
        policy_type=args_cli.residual_policy_type,
        pretrained_name_or_path=policy_ckpt,
        actions_per_chunk=action_horizon,
        device=args_cli.device,
    )
    try:
        return LeRobotServicePolicyClient(force_must_go=args_cli.residual_policy_must_go, **service_kwargs)
    except TypeError:
        return LeRobotServicePolicyClient(**service_kwargs)


def _extract_state(obs_dict: dict, state_source: str) -> np.ndarray:
    if state_source == "policy":
        pol = obs_dict["policy"]
        if torch.is_tensor(pol):
            if pol.ndim == 2:
                pol = pol[0]
            return pol.detach().cpu().numpy().astype(np.float32).reshape(-1)
        return np.asarray(pol, dtype=np.float32).reshape(-1)
    joint = obs_dict["record"]["joint_pos_abs"][0]
    arr = joint.detach().cpu().numpy() if torch.is_tensor(joint) else np.asarray(joint)
    return arr.astype(np.float32).reshape(-1)[:6]


def _build_residual_collection_policy(env, residual_checkpoint_path: str, device: torch.device) -> ResidualCollectionPolicy:
    ckpt = torch.load(residual_checkpoint_path, map_location="cpu")
    ckpt_args = ckpt.get("args", {})
    if not isinstance(ckpt_args, dict):
        ckpt_args = {}
    policy_backend = str(args_cli.residual_policy_backend or ckpt_args.get("policy_backend", "local"))
    policy_ckpt = str(args_cli.residual_base_policy_checkpoint_path or ckpt_args.get("policy_checkpoint_path", ""))
    if not policy_ckpt:
        raise ValueError(
            "--residual_base_policy_checkpoint_path is required when residual checkpoint args do not include policy_checkpoint_path."
        )
    action_horizon = int(
        args_cli.residual_policy_action_horizon
        if args_cli.residual_policy_action_horizon is not None
        else ckpt_args.get("policy_action_horizon", 1)
    )
    state_source = str(ckpt_args.get("state_source", "record_joint6"))
    residual_scale = float(ckpt_args.get("residual_scale", 0.05))
    residual_scale_min = float(ckpt_args.get("residual_scale_min", 0.01))
    residual_scale_max = float(ckpt_args.get("residual_scale_max", 0.2))
    obs_encoder_mode = str(ckpt_args.get("obs_encoder", "state"))
    task_type = get_task_type(args_cli.task)
    base_policy = _build_policy_client(env, task_type, policy_backend, policy_ckpt, action_horizon)
    low, high = _get_action_bounds(env, device)
    if hasattr(env, "get_observations"):
        obs0 = env.get_observations()
    else:
        obs0 = _reset_env_obs(env)

    vit_encoder: EvalVisualObsEncoder | None = None
    state_dim = int(_extract_state(obs0, state_source).shape[0])
    if obs_encoder_mode == "vit":
        obs_encoder_state = ckpt.get("obs_encoder")
        if not isinstance(obs_encoder_state, dict):
            raise RuntimeError("Residual checkpoint expects obs_encoder=vit but has no obs_encoder weights.")
        has_proj = any(k.startswith("front_proj.") or k.startswith("wrist_proj.") for k in obs_encoder_state.keys())
        project_tokens = bool(ckpt_args.get("obs_vit_project_tokens", has_proj))
        if has_proj:
            project_tokens = True
        vit_encoder = EvalVisualObsEncoder(
            device=device,
            state_dim=state_dim,
            vit_image_size=int(ckpt_args.get("obs_vit_image_size", 84)),
            vit_depth=int(ckpt_args.get("obs_vit_depth", 1)),
            vit_embed_dim=int(ckpt_args.get("obs_vit_embed_dim", 128)),
            vit_num_heads=int(ckpt_args.get("obs_vit_num_heads", 4)),
            vit_patch_size=int(ckpt_args.get("obs_vit_patch_size", 8)),
            vit_proj_dim=int(ckpt_args.get("obs_vit_proj_dim", 128)),
            project_tokens=project_tokens,
        ).to(device)
        vit_encoder.load_state_dict(obs_encoder_state)
        vit_encoder.eval()
        obs_dim = int(vit_encoder.output_dim)

        def _state_extractor(obs_dict: dict) -> np.ndarray:
            front = obs_dict["record"]["front"][0]
            wrist = obs_dict["record"]["wrist"][0]
            encoded = vit_encoder.encode_single_no_grad(front=front, wrist=wrist, joint_state=_extract_state(obs_dict, state_source))
            return encoded.detach().cpu().numpy().astype(np.float32).reshape(-1)

    else:
        obs_dim = state_dim

        def _state_extractor(obs_dict: dict) -> np.ndarray:
            return _extract_state(obs_dict, state_source)

    actor_state = ckpt.get("actor")
    if not isinstance(actor_state, dict):
        raise RuntimeError("Residual checkpoint is missing a valid 'actor' state_dict.")
    has_gate_weights = any(str(k).startswith("gate_net.") for k in actor_state.keys())
    use_state_gate = bool(ckpt_args.get("use_state_gate", has_gate_weights))
    if use_state_gate and not has_gate_weights:
        print("[WARN] Checkpoint has no gate weights; forcing use_state_gate=False for compatibility.")
        use_state_gate = False

    actor = ResidualActor(
        obs_dim=obs_dim,
        action_dim=int(low.shape[0]),
        hidden_dim=int(ckpt_args.get("hidden_dim", 256)),
        num_layers=int(ckpt_args.get("actor_num_layers", 2)),
        use_layer_norm=bool(ckpt_args.get("use_layer_norm", True)),
        use_state_gate=use_state_gate,
        gate_hidden_dim=int(ckpt_args.get("gate_hidden_dim", 64)),
        gate_init_bias=float(ckpt_args.get("gate_init_bias", -2.0)),
    ).to(device)
    try:
        actor.load_state_dict(actor_state)
    except RuntimeError as exc:
        # Some older checkpoints omit use_state_gate in args; retry with auto-inferred opposite setting.
        retry_use_state_gate = not use_state_gate
        retry_actor = ResidualActor(
            obs_dim=obs_dim,
            action_dim=int(low.shape[0]),
            hidden_dim=int(ckpt_args.get("hidden_dim", 256)),
            num_layers=int(ckpt_args.get("actor_num_layers", 2)),
            use_layer_norm=bool(ckpt_args.get("use_layer_norm", True)),
            use_state_gate=retry_use_state_gate,
            gate_hidden_dim=int(ckpt_args.get("gate_hidden_dim", 64)),
            gate_init_bias=float(ckpt_args.get("gate_init_bias", -2.0)),
        ).to(device)
        retry_actor.load_state_dict(actor_state)
        actor = retry_actor
        use_state_gate = retry_use_state_gate
        print(f"[WARN] Retried actor load with use_state_gate={use_state_gate} due to: {exc}")
    actor.eval()

    print(
        f"[INFO] Residual collection policy loaded: residual_ckpt={residual_checkpoint_path}, "
        f"base_policy={policy_ckpt}, backend={policy_backend}, obs_encoder={obs_encoder_mode}, "
        f"state_source={state_source}, residual_scale={residual_scale}, use_state_gate={use_state_gate}"
    )
    return ResidualCollectionPolicy(
        actor=actor,
        base_policy=base_policy,
        state_extractor=_state_extractor,
        residual_scale=residual_scale,
        residual_scale_min=residual_scale_min,
        residual_scale_max=residual_scale_max,
        action_low=low,
        action_high=high,
        device=device,
        prompt=str(getattr(env.unwrapped.cfg, "task_description", "Lift the red cube up.")),
    )


def _set_manual_success(env, success: bool) -> None:
    env = env.unwrapped
    if not hasattr(env, "termination_manager"):
        raise RuntimeError("Manual success marking currently requires a manager-based environment.")
    env.termination_manager.set_term_cfg(
        "success",
        TerminationTermCfg(
            func=lambda env: torch.full((env.num_envs,), success, dtype=torch.bool, device=env.device),
        ),
    )
    env.termination_manager.compute()


def _limit_action_delta(
    actions: torch.Tensor,
    previous_actions: torch.Tensor | None,
    max_delta: float,
    limit_gripper: bool,
) -> torch.Tensor:
    """Clamp per-step policy action changes to make teacher trajectories easier to imitate."""
    if max_delta <= 0.0 or previous_actions is None:
        return actions

    limited_actions = actions.clone()
    delta = torch.clamp(actions - previous_actions, min=-max_delta, max=max_delta)
    if limit_gripper:
        limited_actions = previous_actions + delta
    else:
        # SO-101 action layout is 5 arm joints + gripper. Keep gripper responsive by default.
        limited_actions[..., :-1] = previous_actions[..., :-1] + delta[..., :-1]
    return limited_actions


def _warmup_after_reset(env, num_steps: int) -> None:
    """Let sensors/rendering settle after reset without advancing policy-controlled episode frames."""
    for _ in range(max(num_steps, 0)):
        env.unwrapped.sim.render()


def _reset_env_obs(env):
    """Reset env and always return observation dict."""
    reset_out = env.reset()
    if isinstance(reset_out, tuple):
        return reset_out[0]
    return reset_out


def _step_env_obs(env, actions):
    """Step env and return (obs, done_tensor_or_none)."""
    step_out = env.step(actions)
    if isinstance(step_out, tuple) and len(step_out) == 5:
        obs, _reward, terminated, truncated, _info = step_out
        done = terminated | truncated
        return obs, done
    if isinstance(step_out, tuple) and len(step_out) == 4:
        obs, _reward, done, _info = step_out
        return obs, done
    raise RuntimeError("Unexpected env.step output format in collection loop.")


class ManualDecisionController:
    """Keyboard callbacks for manual dataset decisions during automated teacher rollout."""

    def __init__(self):
        self._appwindow = omni.appwindow.get_default_app_window()
        self._input = carb.input.acquire_input_interface()
        self._keyboard = self._appwindow.get_keyboard()
        self._keyboard_sub = self._input.subscribe_to_keyboard_events(self._keyboard, self._on_keyboard_event)
        self.start_recording = False
        self.mark_success = False
        self.reset_failed = False

    def __del__(self):
        if hasattr(self, "_input") and hasattr(self, "_keyboard") and hasattr(self, "_keyboard_sub"):
            self._input.unsubscribe_from_keyboard_events(self._keyboard, self._keyboard_sub)
            self._keyboard_sub = None

    def reset_flags(self):
        self.start_recording = False
        self.mark_success = False
        self.reset_failed = False

    def _on_keyboard_event(self, event, *args, **kwargs):
        if event.type == carb.input.KeyboardEventType.KEY_PRESS:
            if event.input.name == "B":
                self.start_recording = True
            elif event.input.name == "N":
                self.mark_success = True
            elif event.input.name == "R":
                self.reset_failed = True
        return True


